	private void PositionTooltip()
	{
		RectTransform rectTransform = tooltipInstance.transform as RectTransform;
		Vector3 position = Input.mousePosition + new Vector3(12f, -12f, 0f);
		float num = ((overlayCanvas != null) ? overlayCanvas.scaleFactor : 1f);
		float num2 = rectTransform.rect.width * num;
		float num3 = rectTransform.rect.height * num;
		if (LetterboxManager.DockRoot != null && rectTransform.parent == LetterboxManager.DockRoot)
		{
			position.x = Mathf.Min(position.x, (float)Screen.width - num2);
			position.y = Mathf.Max(position.y, num3);
		}
		else
		{
			position.x = Mathf.Min(position.x, (float)(LetterboxManager.GameAreaX + LetterboxManager.GameAreaWidth) - num2);
			position.y = Mathf.Max(position.y, (float)LetterboxManager.GameAreaY + num3);
		}
		position.z = rectTransform.position.z;
		rectTransform.position = position;
	}

	public void ShowHoldRing(float progress)
	{
		EnsureHoldRing();
		FollowDock(holdRingInstance.transform);
		if (!holdRingInstance.activeSelf)
		{
			holdRingInstance.SetActive(value: true);
		}
		holdRingInstance.transform.SetAsLastSibling();
		holdRingFill.fillAmount = Mathf.Clamp01(progress);
		Vector3 mousePosition = Input.mousePosition;
		mousePosition.z = holdRingInstance.transform.position.z;
		holdRingInstance.transform.position = mousePosition;
	}

	private void FollowDock(Transform popup)
	{
		Canvas dockCanvas = LetterboxManager.DockCanvas;
		RectTransform dockRoot = LetterboxManager.DockRoot;
		bool flag = dockCanvas != null && dockRoot != null && dockCanvas.scaleFactor > 0f;
		popup.SetParent(flag ? dockRoot : OverlayRoot(), worldPositionStays: false);
		float num = ((overlayCanvas != null) ? overlayCanvas.scaleFactor : 1f);
		popup.localScale = (flag ? (Vector3.one * (num / dockCanvas.scaleFactor)) : Vector3.one);
		Vector3 localPosition = popup.localPosition;
		localPosition.z = 0f;
		popup.localPosition = localPosition;
	}

