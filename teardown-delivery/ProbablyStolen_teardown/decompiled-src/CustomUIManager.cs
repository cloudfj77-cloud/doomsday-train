	private Sprite GetHoldRingSprite()
	{
		if (holdRingSprite != null)
		{
			return holdRingSprite;
		}
		float num = 31.5f;
		float num2 = 31f;
		float num3 = num2 * 0.62f;
		Texture2D texture2D = new Texture2D(64, 64, TextureFormat.RGBA32, mipChain: false)
		{
			filterMode = FilterMode.Bilinear,
			wrapMode = TextureWrapMode.Clamp
		};
		Color32[] array = new Color32[4096];
		for (int i = 0; i < 64; i++)
		{
			for (int j = 0; j < 64; j++)
			{
				float num4 = (float)j - num;
				float num5 = (float)i - num;
				float num6 = Mathf.Sqrt(num4 * num4 + num5 * num5);
				float num7 = Mathf.Clamp01(Mathf.Min(num2 - num6, num6 - num3));
				array[i * 64 + j] = new Color32(byte.MaxValue, byte.MaxValue, byte.MaxValue, (byte)(num7 * 255f));
			}
		}
		texture2D.SetPixels32(array);
		texture2D.Apply();
		holdRingSprite = Sprite.Create(texture2D, new Rect(0f, 0f, 64f, 64f), new Vector2(0.5f, 0.5f), 100f);
		return holdRingSprite;
	}
