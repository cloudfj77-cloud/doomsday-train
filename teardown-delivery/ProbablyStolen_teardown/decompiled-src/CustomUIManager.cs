	private void EnsureHoldRing()
	{
		if (!(holdRingInstance != null))
		{
			EnsureOverlayCanvas();
			holdRingInstance = new GameObject("hold_ring", typeof(RectTransform));
			RectTransform rectTransform = (RectTransform)holdRingInstance.transform;
			rectTransform.SetParent(OverlayRoot(), worldPositionStays: false);
			rectTransform.sizeDelta = new Vector2(40f, 40f);
			CanvasGroup canvasGroup = holdRingInstance.AddComponent<CanvasGroup>();
			canvasGroup.blocksRaycasts = false;
			canvasGroup.interactable = false;
			Sprite sprite = GetHoldRingSprite();
			Image image = CreateHoldRingImage("background", rectTransform, sprite);
			Color color = RenderHandler.GetColorFromPalette(RenderHandler.ColorPalette.Black);
			color.a = 0.55f;
			image.color = color;
			holdRingFill = CreateHoldRingImage("fill", rectTransform, sprite);
			holdRingFill.color = new Color32(225, 209, 156, byte.MaxValue);
			holdRingFill.type = Image.Type.Filled;
			holdRingFill.fillMethod = Image.FillMethod.Radial360;
			holdRingFill.fillOrigin = 2;
			holdRingFill.fillClockwise = true;
			holdRingFill.fillAmount = 0f;
			holdRingInstance.SetActive(value: false);
		}
	}

