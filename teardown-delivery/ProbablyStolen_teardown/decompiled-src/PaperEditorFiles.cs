using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using UnityEngine;

public static class PaperEditorFiles
{
	public static string SanitizeId(string raw)
	{
		if (string.IsNullOrEmpty(raw))
		{
			return "";
		}
		StringBuilder stringBuilder = new StringBuilder(raw.Length);
		string text = raw.Trim().ToLowerInvariant();
		foreach (char c in text)
		{
			stringBuilder.Append((char.IsLetterOrDigit(c) || c == '_') ? c : '_');
		}
		return stringBuilder.ToString().Trim('_');
	}

	public static List<LoadedMod> LocalMods()
	{
		return ModLoader.Mods.Where((LoadedMod m) => m.Source == ModSource.Local && m.IsEnabled).ToList();
	}

	public static void CopyJson(PaperEditor editor)
	{
		if (editor.IsEditing)
		{
			GUIUtility.systemCopyBuffer = PaperJson.Serialize(editor.Data);
			editor.SetStatus("Book JSON copied to the clipboard");
		}
	}

	public static void CopyCSharp(PaperEditor editor)
	{
		if (editor.IsEditing)
		{
			GUIUtility.systemCopyBuffer = GenerateCSharp(editor.Data, editor.Entry.modId);
			editor.SetStatus("C# snippet copied to the clipboard");
		}
	}

	public static void OpenFolder(PaperEditor editor)
	{
		string text = ((editor.IsEditing && editor.Entry.IsFileBacked) ? Path.GetDirectoryName(editor.Entry.path) : ModLoader.ModsPath);
		if (!string.IsNullOrEmpty(text))
		{
			if (!System.IO.Directory.Exists(text))
			{
				System.IO.Directory.CreateDirectory(text);
			}
			Application.OpenURL("file:///" + Path.GetFullPath(text).Replace('\\', '/'));
		}
	}

	public static void OpenFile(PaperEditor editor)
	{
		if (editor.IsEditing && editor.Entry.IsFileBacked)
		{
			editor.Save();
			Application.OpenURL("file:///" + Path.GetFullPath(editor.Entry.path).Replace('\\', '/'));
		}
	}

	public static string GenerateCSharp(PaperBookData data, string modId)
	{
		StringBuilder stringBuilder = new StringBuilder();
		string text = Quote(modId ?? "my_mod");
		stringBuilder.AppendLine("// Generated by the paper editor. The fluent API covers pages and elements; not expressed here:");
		stringBuilder.AppendLine("// the book's own templates (pages name them, so register the JSON with ModHelper.RegisterPaperBook");
		stringBuilder.AppendLine("// when you need them), a custom chrome layout, designWidth/designHeight, border, title, draggable/zoomable.");
		if (data.templates.Count > 0)
		{
			stringBuilder.AppendLine("// TODO: templates not emitted: " + string.Join(", ", data.templates.Select((PaperTemplateData t) => t.id)));
		}
		if (data.designWidth > 0f || data.designHeight > 0f)
		{
			stringBuilder.AppendLine("// TODO: coordinates below are in a " + F(data.designWidth) + " x " + F(data.designHeight) + " design space (designWidth/designHeight).");
		}
		stringBuilder.AppendLine("PaperUI ui = ModHelper.CreatePaper(" + text + ", " + Quote(data.id) + ", " + Quote(data.background) + ", " + F(data.width) + ", " + F(data.height) + ");");
		bool value = data.chrome.Any((PaperElementData e) => e.action == "close");
		bool value2 = data.chrome.Any((PaperElementData e) => e.action == "zoom");
		bool value3 = data.chrome.Any((PaperElementData e) => e.action == "flip_left" || e.action == "flip_right");
		bool value4 = data.chrome.Any((PaperElementData e) => e.action == "page_indicator");
		stringBuilder.AppendLine("ui.SetChrome(close: " + B(value) + ", zoom: " + B(value2) + ", flip: " + B(value3) + ", pageIndicator: " + B(value4) + ");");
		if (data.posX != 0f || data.posY != 0f)
		{
			stringBuilder.AppendLine("ui.SetPosition(" + F(data.posX) + ", " + F(data.posY) + ");");
		}
		if (!data.sounds)
		{
			stringBuilder.AppendLine("ui.SetSounds(false);");
		}
		foreach (PaperPageData page in data.pages)
		{
			stringBuilder.AppendLine(string.IsNullOrEmpty(page.template) ? ("ui.AddPage(" + Quote(page.name) + ");") : ("ui.AddPage(" + Quote(page.name) + ", template: " + Quote(page.template) + ");"));
			foreach (KeyValuePair<string, string> slot in page.slots)
			{
				stringBuilder.AppendLine("ui.SetSlot(" + Quote(slot.Key) + ", " + Quote(slot.Value) + ");");
			}
			foreach (PaperElementData element in page.elements)
			{
				AppendElement(stringBuilder, element);
			}
		}
		stringBuilder.AppendLine("ui.Show();");
		return stringBuilder.ToString();
	}

	private static void AppendElement(StringBuilder sb, PaperElementData e)
	{
		string text = (string.IsNullOrEmpty(e.id) ? "null" : Quote(e.id));
		switch (e.type)
		{
		case "flow":
			sb.AppendLine("ui.AddFlow(" + F(e.x) + ", " + F(e.y) + ", " + F(e.w) + ", " + F(e.h) + ", " + Quote(e.id ?? "flow") + ", spacing: " + F(e.spacing) + ", align: " + Quote(e.align) + ");");
			break;
		case "image":
			sb.AppendLine("ui.AddImage(" + F(e.x) + ", " + F(e.y) + ", " + F(e.w) + ", " + F(e.h) + ", " + Quote(e.sprite) + ", fit: " + Quote(e.fit) + ", id: " + text + ");");
			break;
		case "line":
			sb.AppendLine("ui.AddLine(" + F(e.x) + ", " + F(e.y) + ", " + F(e.x2) + ", " + F(e.y2) + ", thickness: " + F(e.thickness) + ", color: " + Quote(e.color) + ", arrow: " + Quote(e.arrow ?? "none") + ", id: " + text + ");");
			break;
		case "button":
			if (e.IsIconButton)
			{
				sb.AppendLine("ui.AddIconButton(" + F(e.x) + ", " + F(e.y) + ", " + F(e.w) + ", " + F(e.h) + ", " + Quote(e.sprite) + ", () => { /* " + e.action + " */ }, id: " + text + ", action: " + Quote(e.action) + ");");
			}
			else
			{
				sb.AppendLine("ui.AddButton(" + F(e.x) + ", " + F(e.y) + ", " + F(e.w) + ", " + F(e.h) + ", " + Quote(e.text) + ", () => { /* " + e.action + " */ }, id: " + text + ", action: " + Quote(e.action) + ");");
			}
			break;
		default:
			if (!string.IsNullOrEmpty(e.flow))
			{
				sb.AppendLine("ui.AddFlowText(" + Quote(e.flow) + ", " + Quote(e.text) + ", " + Quote(e.style) + ", id: " + text + ", width: " + F(e.w) + ");");
			}
			else if (!string.IsNullOrEmpty(e.loc))
			{
				sb.AppendLine("ui.AddLocalizedText(" + F(e.x) + ", " + F(e.y) + ", " + F(e.w) + ", " + F(e.h) + ", " + Quote(e.loc) + ", " + Quote(e.style) + ", id: " + text + ", align: " + Quote(e.align) + ", fontSize: " + F(e.fontSize) + ");");
			}
			else
			{
				sb.AppendLine("ui.AddText(" + F(e.x) + ", " + F(e.y) + ", " + F(e.w) + ", " + F(e.h) + ", " + Quote(e.text) + ", " + Quote(e.style) + ", id: " + text + ", align: " + Quote(e.align) + ", fontSize: " + F(e.fontSize) + ");");
			}
			break;
		}
		List<string> list = new List<string>();
		if (!e.visible)
		{
			list.Add("ui.Last.visible = false;");
		}
		if (e.autoHeight && string.IsNullOrEmpty(e.flow))
		{
			list.Add("ui.Last.autoHeight = true;");
		}
		if (!string.IsNullOrEmpty(e.color) && !e.IsLine)
		{
			list.Add("ui.Last.color = " + Quote(e.color) + ";");
		}
		if (e.IsImage && Mathf.Abs(e.scale - 1f) > 0.001f)
		{
			list.Add("ui.Last.scale = " + F(e.scale) + ";");
		}
		if (e.IsImage && e.silhouette)
		{
			list.Add("ui.Last.silhouette = true;");
		}
		if (e.IsImage && !string.IsNullOrEmpty(e.fill))
		{
			list.Add("ui.Last.fill = " + Quote(e.fill) + ";");
		}
		if (e.IsLine && Mathf.Abs(e.arrowSize - 8f) > 0.001f)
		{
			list.Add("ui.Last.arrowSize = " + F(e.arrowSize) + ";");
		}
		if (e.translations != null && e.translations.Count > 0)
		{
			list.Add("// TODO: translations not emitted (" + string.Join(", ", e.translations.Keys) + "); set ui.Last.translations or use loc keys.");
		}
		if (e.valign != "top")
		{
			list.Add("ui.Last.valign = " + Quote(e.valign) + ";");
		}
		if (!e.wrap)
		{
			list.Add("ui.Last.wrap = false;");
		}
		if (e.raycast)
		{
			list.Add("ui.Last.raycast = true;");
		}
		if (!string.IsNullOrEmpty(e.hoverSprite))
		{
			list.Add("ui.Last.hoverSprite = " + Quote(e.hoverSprite) + ";");
		}
		foreach (string item in list)
		{
			sb.AppendLine(item);
		}
	}

	private static string Quote(string value)
	{
		if (value == null)
		{
			return "null";
		}
		return "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "\\r")
			.Replace("\n", "\\n")
			.Replace("\t", "\\t") + "\"";
	}

	private static string F(float value)
	{
		return value.ToString("0.##", CultureInfo.InvariantCulture) + "f";
	}

	private static string B(bool value)
	{
		if (!value)
		{
			return "false";
		}
		return "true";
	}

	public static void Screenshot(PaperEditor editor)
	{
		if (editor.IsEditing)
		{
			editor.StartCoroutine(ScreenshotRoutine(editor));
		}
	}

	private static IEnumerator ScreenshotRoutine(PaperEditor editor)
	{
		PaperUI ui = editor.Ui;
		if (editor.Overlay != null)
		{
			editor.Overlay.Visible = false;
		}
		PaperEditorWindow.SetVisible(visible: false);
		yield return new WaitForEndOfFrame();
		Texture2D texture2D = ScreenCapture.CaptureScreenshotAsTexture();
		if (editor.Overlay != null)
		{
			editor.Overlay.Visible = true;
		}
		PaperEditorWindow.SetVisible(visible: true);
		if (ui?.Rect == null || texture2D == null)
		{
			yield break;
		}
		Canvas componentInParent = ui.Root.GetComponentInParent<Canvas>();
		Camera cam = ((componentInParent != null && componentInParent.renderMode != 0) ? componentInParent.worldCamera : null);
		Vector3[] array = new Vector3[4];
		ui.Rect.GetWorldCorners(array);
		Vector2 vector = RectTransformUtility.WorldToScreenPoint(cam, array[0]);
		Vector2 vector2 = RectTransformUtility.WorldToScreenPoint(cam, array[2]);
		int num = Mathf.Clamp(Mathf.FloorToInt(Mathf.Min(vector.x, vector2.x)), 0, texture2D.width - 1);
		int num2 = Mathf.Clamp(Mathf.FloorToInt(Mathf.Min(vector.y, vector2.y)), 0, texture2D.height - 1);
		int num3 = Mathf.Clamp(Mathf.CeilToInt(Mathf.Abs(vector2.x - vector.x)), 1, texture2D.width - num);
		int num4 = Mathf.Clamp(Mathf.CeilToInt(Mathf.Abs(vector2.y - vector.y)), 1, texture2D.height - num2);
		Texture2D texture2D2 = new Texture2D(num3, num4, TextureFormat.RGBA32, mipChain: false);
		texture2D2.SetPixels(texture2D.GetPixels(num, num2, num3, num4));
		texture2D2.Apply();
		byte[] bytes = texture2D2.EncodeToPNG();
		UnityEngine.Object.Destroy(texture2D);
		UnityEngine.Object.Destroy(texture2D2);
		string text = Path.Combine(editor.Entry.IsFileBacked ? Path.GetDirectoryName(editor.Entry.path) : ModLoader.ModsPath, $"{editor.Entry.bookId}_page{ui.CurrentPage + 1}.png");
		try
		{
			File.WriteAllBytes(text, bytes);
			editor.SetStatus("Screenshot saved: " + text);
		}
		catch (Exception ex)
		{
			editor.SetStatus("Screenshot failed: " + ex.Message);
		}
	}
}
