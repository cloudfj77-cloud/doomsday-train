	public CustomUIBuilder CreateWindow(string id, string title = null, string layerId = "overlay", GameObject windowPrefabOverride = null, Style style = Style.Auto)
	{
		StallWatchdog.Crumb("customui " + id);
		PruneDeadWindows();
		if (windowsById.TryGetValue(id, out var value))
		{
			value.Close();
		}
		CustomUICanvasAnchor customUICanvasAnchor = ResolveAnchor(layerId);
		RectTransform parent = ((customUICanvasAnchor != null) ? customUICanvasAnchor.Root : OverlayRoot());
		CustomUIWindow customUIWindow = new CustomUIWindow
		{
			id = id,
			layerId = layerId,
			useMetaPrefabs = style switch
			{
				Style.Auto => IsMetaLayer(layerId), 
				Style.Meta => true, 
				_ => false, 
			},
			useMachineryStyle = (style == Style.Machinery)
		};
		GameObject gameObject = ((windowPrefabOverride != null) ? windowPrefabOverride : windowPrefab);
		if (style == Style.Machinery && windowPrefabOverride == null)
		{
			customUIWindow.root = CustomUIMachineryStyle.CreateFrame(parent);
			customUIWindow.root.name = "custom_window_" + id;
			customUIWindow.frame = customUIWindow.root.GetComponent<CustomUIWindowFrame>();
		}
		else if (gameObject == null)
		{
			Debug.LogError("[CustomUI] No windowPrefab assigned on CustomUIManager");
			customUIWindow.root = new GameObject("custom_window_" + id, typeof(RectTransform));
			customUIWindow.root.transform.SetParent(parent, worldPositionStays: false);
			VerticalLayoutGroup verticalLayoutGroup = customUIWindow.root.AddComponent<VerticalLayoutGroup>();
			verticalLayoutGroup.childControlWidth = true;
			verticalLayoutGroup.childControlHeight = true;
			verticalLayoutGroup.childForceExpandWidth = false;
			verticalLayoutGroup.childForceExpandHeight = false;
		}
		else
		{
			customUIWindow.root = UnityEngine.Object.Instantiate(gameObject, parent);
			customUIWindow.root.name = "custom_window_" + id;
			customUIWindow.frame = customUIWindow.root.GetComponent<CustomUIWindowFrame>();
			if (customUIWindow.frame == null)
			{
				Debug.LogError("[CustomUI] window prefab '" + gameObject.name + "' has no CustomUIWindowFrame, content goes on the window root");
			}
		}
		if (customUICanvasAnchor != null && customUICanvasAnchor.attachStoreUI)
		{
			customUIWindow.root.AddComponent<StoreUI>().isPaperUI = customUICanvasAnchor.isPaperUI;
			if (customUICanvasAnchor.isPaperUI && customUIWindow.root.GetComponent<PaperPanelFocusStamp>() == null)
			{
				customUIWindow.root.AddComponent<PaperPanelFocusStamp>();
			}
		}
		if (title != null)
		{
			customUIWindow.SetTitle(title);
		}
		if (customUIWindow.frame != null && customUIWindow.frame.closeButton != null)
		{
			customUIWindow.frame.closeButton.onClick.AddListener(customUIWindow.Close);
		}
		windowsById[id] = customUIWindow;
		windowOrder.Add(customUIWindow);
		return new CustomUIBuilder(this, customUIWindow);
	}

	public GameObject SpawnElement(ElementKind kind, Transform parent, CustomUIWindow window, string name)
	{
		if (window != null && window.useMachineryStyle)
		{
			GameObject gameObject = CustomUIMachineryStyle.Create(kind, parent);
			if (gameObject != null)
			{
				gameObject.name = name;
				return gameObject;
			}
			GameObject prefab = GetPrefab(kind, meta: false);
			if (prefab == null)
			{
				return null;
			}
			GameObject obj = UnityEngine.Object.Instantiate(prefab, parent);
			obj.name = name;
			CustomUIMachineryStyle.Reskin(obj);
			return obj;
		}
		GameObject prefab2 = GetPrefab(kind, window?.useMetaPrefabs ?? false);
		if (prefab2 == null)
		{
			return null;
		}
		GameObject obj2 = UnityEngine.Object.Instantiate(prefab2, parent);
		obj2.name = name;
		return obj2;
	}

	public CustomUIBuilder BuildInto(RectTransform container, bool useMetaPrefabs = true, string id = null)
	{
		if (container == null)
		{
			Debug.LogError("[CustomUI] BuildInto needs a container");
			return null;
		}
		if (container.GetComponent<LayoutGroup>() == null)
		{
			VerticalLayoutGroup verticalLayoutGroup = container.gameObject.AddComponent<VerticalLayoutGroup>();
			verticalLayoutGroup.spacing = 8f;
			verticalLayoutGroup.childControlWidth = true;
			verticalLayoutGroup.childControlHeight = true;
			verticalLayoutGroup.childForceExpandWidth = false;
			verticalLayoutGroup.childForceExpandHeight = false;
		}
		CustomUIWindow window = new CustomUIWindow
		{
			id = (string.IsNullOrEmpty(id) ? container.name : id),
			layerId = null,
			root = container.gameObject,
			useMetaPrefabs = useMetaPrefabs
		};
		return new CustomUIBuilder(this, window, container);
	}

	public CustomUIWindow GetWindow(string id)
	{
		PruneDeadWindows();
		if (!windowsById.TryGetValue(id, out var value))
		{
			return null;
		}
		return value;
	}

	public bool IsOpen(string id)
	{
		return GetWindow(id)?.IsVisible ?? false;
	}

