	{
		GetWindow(id)?.Close();
	}

	public void CloseAllWindows()
	{
		PruneDeadWindows();
		foreach (CustomUIWindow item in new List<CustomUIWindow>(windowOrder))
		{
			item.Close();
		}
	}

	public CustomUIElement GetElement(string windowId, string elementId)
	{
		return GetWindow(windowId)?.Get(elementId);
	}

	public void NotifyWindowClosed(CustomUIWindow window)
	{
		windowOrder.Remove(window);
		if (windowsById.TryGetValue(window.id, out var value) && value == window)
		{
			windowsById.Remove(window.id);
		}
	}

	private void PruneDeadWindows()
	{
		for (int num = windowOrder.Count - 1; num >= 0; num--)
		{
			CustomUIWindow customUIWindow = windowOrder[num];
			if (!customUIWindow.IsAlive)
			{
				windowOrder.RemoveAt(num);
				if (windowsById.TryGetValue(customUIWindow.id, out var value) && value == customUIWindow)
				{
					windowsById.Remove(customUIWindow.id);
				}
			}
		}
	}

	private void HandleEscape()
	{
		if (!KeyBindHelper.GetBackDown() || StoreUIManager.IsTextFieldFocused())
		{
			return;
		}
		for (int num = windowOrder.Count - 1; num >= 0; num--)
		{
			CustomUIWindow customUIWindow = windowOrder[num];
			if (customUIWindow.IsAlive && customUIWindow.IsVisible && customUIWindow.closeOnEscape)
			{
				consumedEscapeFrame = Time.frameCount;
				customUIWindow.Close();
				break;
			}
		}
	}

	public bool HasEscapeTarget()
	{
		if (consumedEscapeFrame == Time.frameCount)
		{
			return true;
		}
		for (int num = windowOrder.Count - 1; num >= 0; num--)
		{
			CustomUIWindow customUIWindow = windowOrder[num];
			if (customUIWindow.IsAlive && customUIWindow.IsVisible && customUIWindow.closeOnEscape)
			{
				return true;
			}
		}
		return false;
	}

	public static void RegisterAnchor(CustomUICanvasAnchor anchor)
	{
		if (!(anchor == null) && !string.IsNullOrEmpty(anchor.layerId))
		{
			if (anchors.TryGetValue(anchor.layerId, out var value) && value != null && value != anchor)
			{
				Debug.LogWarning("[CustomUI] Layer '" + anchor.layerId + "' registered twice, keeping the newest anchor");
			}
			anchors[anchor.layerId] = anchor;
		}
	}

	public static void UnregisterAnchor(CustomUICanvasAnchor anchor)
	{
		if (!(anchor == null) && !string.IsNullOrEmpty(anchor.layerId) && anchors.TryGetValue(anchor.layerId, out var value) && value == anchor)
		{
			anchors.Remove(anchor.layerId);
		}
	}

	public static List<string> GetAvailableLayers()
	{
		List<string> list = new List<string> { "overlay" };
		foreach (KeyValuePair<string, CustomUICanvasAnchor> anchor in anchors)
		{
			if (anchor.Value != null)
			{
				list.Add(anchor.Key);
			}
		}
		return list;
	}

	private CustomUICanvasAnchor ResolveAnchor(string layerId)
	{
		if (string.IsNullOrEmpty(layerId) || layerId == "overlay")
		{
			return null;
		}
		if (anchors.TryGetValue(layerId, out var value) && value != null)
		{
			return value;
		}
		Debug.LogWarning("[CustomUI] No canvas anchor for layer '" + layerId + "' in the current scene, using the overlay layer");
		return null;
	}

	private RectTransform OverlayRoot()
	{
		EnsureOverlayCanvas();
		return overlayCanvas.transform as RectTransform;
	}

	public RectTransform GetLayerRoot(string layerId)
	{
		CustomUICanvasAnchor customUICanvasAnchor = ResolveAnchor(layerId);
		if (!(customUICanvasAnchor != null))
		{
			return OverlayRoot();
		}
		return customUICanvasAnchor.Root;
	}

	public static bool HasLayer(string layerId)
	{
		if (layerId == "overlay")
		{
			return true;
		}
		if (anchors.TryGetValue(layerId, out var value))
		{
			return value != null;
		}
		return false;
	}

	private void EnsureOverlayCanvas()
	{
		if (!(overlayCanvas != null))
		{
			GameObject gameObject = new GameObject("CustomUIOverlayCanvas", typeof(RectTransform));
			gameObject.transform.SetParent(base.transform, worldPositionStays: false);
			overlayCanvas = gameObject.AddComponent<Canvas>();
			overlayCanvas.renderMode = RenderMode.ScreenSpaceOverlay;
			overlayCanvas.sortingOrder = 900;
			AddScreenScaler(gameObject);
			gameObject.AddComponent<GraphicRaycaster>();
		}
	}

	public static CanvasScaler AddScreenScaler(GameObject canvasObject)
	{
		CanvasScaler canvasScaler = canvasObject.GetComponent<CanvasScaler>();
		if (canvasScaler == null)
		{
			canvasScaler = canvasObject.AddComponent<CanvasScaler>();
		}
		canvasScaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
		canvasScaler.referenceResolution = new Vector2(1920f, 1080f);
		canvasScaler.screenMatchMode = CanvasScaler.ScreenMatchMode.MatchWidthOrHeight;
		canvasScaler.matchWidthOrHeight = 0f;
		return canvasScaler;
	}

	private void BuildSpriteDict()
	{
		spriteDict.Clear();
		foreach (SpriteEntry spriteEntry in spriteEntries)
		{
			if (spriteEntry != null && !string.IsNullOrEmpty(spriteEntry.key) && !(spriteEntry.sprite == null))
			{
				if (spriteDict.ContainsKey(spriteEntry.key))
				{
					Debug.LogWarning("[CustomUI] Duplicate sprite key '" + spriteEntry.key + "', keeping the first");
				}
				else
				{
					spriteDict[spriteEntry.key] = spriteEntry.sprite;
				}
			}
		}
	}

	private void BuildMetaSprites()
	{
		metaSprites = new Dictionary<string, Sprite>();
		GameObject[] array = new GameObject[9] { metaPanelPrefab, metaButtonPrefab, metaCloseButtonPrefab, metaSeparatorPrefab, metaSliderPrefab, metaTogglePrefab, metaTextfieldPrefab, metaDropdownPrefab, metaScrollViewPrefab };
		foreach (GameObject gameObject in array)
		{
			if (gameObject == null)
			{
				continue;
			}
			Image[] componentsInChildren = gameObject.GetComponentsInChildren<Image>(includeInactive: true);
			foreach (Image image in componentsInChildren)
			{
				if (!(image.sprite == null))
				{
					string key = "meta_" + image.sprite.name;
					if (!metaSprites.ContainsKey(key))
					{
						metaSprites[key] = image.sprite;
					}
				}
			}
		}
		NewGameSpecializationFrame newGameSpecializationFrame = ((newGameSpecializationPrefab != null) ? newGameSpecializationPrefab.GetComponentInChildren<NewGameSpecializationFrame>(includeInactive: true) : null);
		if (newGameSpecializationFrame?.icons == null)
		{
			return;
		}
		Sprite[] icons = newGameSpecializationFrame.icons;
		foreach (Sprite sprite in icons)
		{
			if (sprite != null && !metaSprites.ContainsKey(sprite.name))
			{
				metaSprites[sprite.name] = sprite;
			}
		}
	}

