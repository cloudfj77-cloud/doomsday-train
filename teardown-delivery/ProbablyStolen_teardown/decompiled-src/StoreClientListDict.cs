	[ES3NonSerializable]
	private static Dictionary<string, string> displayNameCache = new Dictionary<string, string>();

	public static StoreClient CreateStoreClient(string identifier)
	{
		if (storeClientDict.TryGetValue(identifier, out var value))
		{
			StoreClient storeClient = value();
			ModSourceHelper.MarkFromFactory(storeClient, value);
			return storeClient;
		}
		Debug.Log("<color=red>StoreClient with identifier not found In ListDict</color>");
		Debug.LogError("StoreClient with identifier '" + identifier + "' not found.");
		return StoreClientList.CreateScavGeneral();
	}

	public static string GetClientDisplayName(string identifier)
	{
		if (displayNameCache.TryGetValue(identifier, out var value))
		{
			return value;
		}
		if (storeClientDict.TryGetValue(identifier, out var value2))
		{
			string displayName = value2().displayName;
			displayNameCache[identifier] = displayName;
			return displayName;
		}
		Debug.LogError("StoreClient with identifier '" + identifier + "' not found.");
		return "";
	}

	public static void ClearDisplayNameCache()
	{
		displayNameCache.Clear();
	}
