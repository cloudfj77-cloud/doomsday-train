using System;
using System.Collections.Generic;

public class NavDiskHelper
{
	public const string NAV_DISK_TAG = "NAV_DISK_TAG";

	public const string NAV_DISK_MINING_TAG = "NAV_DISK_MINING_TAG";

	public const string NAV_DISK_SALVAGE_TAG = "NAV_DISK_SALVAGE_TAG";

	public const string NAV_DISK_TRADER_STATION_TAG = "NAV_DISK_TRADER_STATION_TAG";

	public const string NAV_DISK_SHELF_LIFE_INT = "NAV_DISK_SHELF_LIFE_INT";

	public const string DESIGNATION_STRING = "DESIGNATION_TAG";

	public const string DESTINATION_STRING = "DESTINATION_STRING";

	public const int NAV_DISK_SHELF_LIFE = 40;

	public static void InitNavDisk(GameItem item)
	{
		item.EnableTag("NAV_DISK_TAG");
		item.SetType("NAV_DISK_TAG");
		item.ModifyTag("NAV_DISK_SHELF_LIFE_INT", delegate(TagState state)
		{
			state.Enable().SetInt(40);
		});
		item.onTurnEndSlotItemFunc = (Action<GameItem, GameInventory, SlotMarker>)Delegate.Combine(item.onTurnEndSlotItemFunc, (Action<GameItem, GameInventory, SlotMarker>)delegate(GameItem item, GameInventory parentInventory, SlotMarker slot)
		{
			int shelfLife = item.GetTagReadonly("NAV_DISK_SHELF_LIFE_INT").GetInt();
			if (shelfLife > 0)
			{
				item.ModifyTag("NAV_DISK_SHELF_LIFE_INT", delegate(TagState state)
				{
					state.Enable().SetInt(shelfLife - 1);
				});
			}
			else
			{
				item.Destroy();
			}
		});
	}

	public static void CreateNavDiskTooltip(RichTextBuilder builder, GameItem item)
	{
		if (item.IsTag("NAV_DISK_TAG"))
		{
			builder.AddLine("   Outdated in " + item.GetTagReadonly("NAV_DISK_SHELF_LIFE_INT").GetInt() + " turns", ignoreEmpty: true, RenderHandler.ColorPalette.LightYellow);
		}
	}

	public static GameItem GenerateNavDiskFromPOI(OverworldPOI poi)
	{
		GameItem gameItem = DirectoryMaster.Item("nav_disk");
		if (poi is OverworldSpace)
		{
			gameItem.name = poi.displayName + " Nav Disk";
			gameItem.shortDescription = "Generated by your ship's Nav System. This data disk contains the necessary navigation information to travel to " + poi.displayName + ". Due to the constant shifts in the subspace, all nav data will become outdated after a while.";
			gameItem.ModifyTag("DESTINATION_STRING", delegate(TagState state)
			{
				state.Enable().SetString(poi.identifier);
			});
			gameItem.unitValue = 50L;
			if (poi.identifier.Equals("mining_asteroid"))
			{
				gameItem.EnableTag("NAV_DISK_MINING_TAG");
			}
			if (poi.identifier.Equals("shipwreck"))
			{
				gameItem.EnableTag("NAV_DISK_SALVAGE_TAG");
			}
		}
		else
		{
			_ = poi is OverworldStation;
		}
		return gameItem;
	}

	public static void HandleNavDiskOnArrivalToPoi()
	{
		GraphUtils.TryAcceptAll(NavigationHelper.GetActiveNavSystem(), GenerateNavDiskFromPOI(GameMaster.current.shipManager.nextPOI));
	}

	public static List<GameItem> GetAllNavDiskFromShipById(string identifier)
	{
		List<GameItem> list = GraphUtils.FindAllChildrenType<GameItem>(GameMaster.current.shipManager.ship);
		List<GameItem> list2 = new List<GameItem>();
		foreach (GameItem item in list)
		{
			if (item.IsTag("NAV_DISK_TAG") && item.GetTagReadonly("DESTINATION_STRING").GetString().Equals(identifier))
			{
				list2.Add(item);
			}
		}
		return list2;
	}
}
