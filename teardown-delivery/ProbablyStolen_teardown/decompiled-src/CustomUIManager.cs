	public Sprite GetSprite(string key, bool quiet)
	{
		if (string.IsNullOrEmpty(key))
		{
			return null;
		}
		int num = key.IndexOf(':');
		if (num > 0)
		{
			return GetModSprite(key.Substring(0, num), key.Substring(num + 1), quiet);
		}
		if (spriteDict.TryGetValue(key, out var value))
		{
			return value;
		}
		if (SpriteDict.Instance != null && SpriteDict.Instance.spriteDictionary != null && SpriteDict.Instance.spriteDictionary.TryGetValue(key, out value))
		{
			return value;
		}
		if ((key.StartsWith("meta_") || key.StartsWith("icons_")) && MetaSprites.TryGetValue(key, out value))
		{
			return value;
		}
		PaperAssetCatalog.Entry entry = PaperAssets.FindInCatalog(key);
		if (entry != null)
		{
			return entry.sprite;
		}
		if (!quiet)
		{
			Debug.LogWarning("[CustomUI] No sprite found for key '" + key + "'");
		}
		return null;
	}

	public Sprite GetModSprite(string modId, string spriteKey)
	{
		return GetModSprite(modId, spriteKey, quiet: false);
	}

	public Sprite GetModSprite(string modId, string spriteKey, bool quiet)
	{
		LoadedMod loadedMod = ModLoader.Mods.Find((LoadedMod m) => m.Manifest.ID == modId);
		if (loadedMod == null)
		{
			if (!quiet)
			{
				Debug.LogWarning("[CustomUI] No loaded mod with id '" + modId + "'");
			}
			return null;
		}
		if (loadedMod.Sprites.TryGetValue(spriteKey, out var value))
		{
			return value;
		}
		if (loadedMod.PaperSprites.TryGetValue(spriteKey, out value))
		{
			return value;
		}
		if (!quiet)
		{
			Debug.LogWarning("[CustomUI] Mod '" + modId + "' has no sprite '" + spriteKey + "'");
		}
		return null;
	}

	public void ShowTooltip(string text, CustomUITooltipTrigger owner)
	{
		if (tooltipInstance == null)
		{
			tooltipInstance = ((tooltipPrefab != null) ? UnityEngine.Object.Instantiate(tooltipPrefab, OverlayRoot()) : BuildDefaultTooltip(OverlayRoot()));
			tooltipInstance.name = "custom_ui_tooltip";
			tooltipText = tooltipInstance.GetComponentInChildren<TextMeshProUGUI>(includeInactive: true);
			CanvasGroup canvasGroup = tooltipInstance.GetComponent<CanvasGroup>();
			if (canvasGroup == null)
			{
				canvasGroup = tooltipInstance.AddComponent<CanvasGroup>();
			}
			canvasGroup.blocksRaycasts = false;
		}
		tooltipOwner = owner;
		if (tooltipText != null)
		{
			tooltipText.text = text;
			LayoutElement component = tooltipText.GetComponent<LayoutElement>();
			if (component != null)
			{
				component.preferredWidth = Mathf.Min(tooltipText.GetPreferredValues(text).x + 1f, 360f);
			}
		}
		FollowDock(tooltipInstance.transform);
		tooltipInstance.SetActive(value: true);
		tooltipInstance.transform.SetAsLastSibling();
		LayoutRebuilder.ForceRebuildLayoutImmediate(tooltipInstance.transform as RectTransform);
		PositionTooltip();
	}

