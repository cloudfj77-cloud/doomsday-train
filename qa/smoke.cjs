const { launch, waitFor, click, shot, wait } = require('./lib.cjs');
(async () => {
  const url = process.argv[2] || 'http://localhost:4195/?qa=1';
  const dir = process.argv[3] || 'artifacts/smoke';
  require('fs').mkdirSync(dir, { recursive: true });
  const { browser, page, errors } = await launch({ lang: process.env.QA_LANG || 'zh-CN' });
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.evaluate(() => localStorage.clear());
  await waitFor(page, (s) => s.engine?.ready, 90000);
  await wait(2500);
  console.log('title', await shot(page, dir, '01-title'));
  await click(page, '[data-act="new-game"]');
  await waitFor(page, (s) => s.game?.day === 1);
  await wait(1500);
  console.log('route', await shot(page, dir, '02-route'));
  await click(page, '[data-act="choose-route"]', 2);
  await wait(800);
  console.log('depot', await shot(page, dir, '03-depot'));
  await click(page, '[data-act="depart"]');
  await wait(1200);
  console.log('travel', await shot(page, dir, '04-travel'));
  await waitFor(page, (s) => !s.travelling);
  await wait(800);
  console.log('station', await shot(page, dir, '05-station'));
  console.log('errors', JSON.stringify(errors.slice(0, 8)));
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
